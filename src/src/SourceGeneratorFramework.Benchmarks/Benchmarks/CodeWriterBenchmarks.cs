using BenchmarkDotNet.Attributes;

namespace Purview.SourceGeneratorFramework.Benchmarks;

[MemoryDiagnoser]
public class CodeWriterBenchmarks
{
	GenerationSettings _settings;

	[GlobalSetup]
	public void Setup()
	{
		_settings = new GenerationSettings("Benchmark", "1.0.0");
	}

	[Benchmark]
	public string ManyClasses()
	{
		var writer = new CodeWriter(_settings, throwOnUnclosedScopes: false);
		writer.AutoGeneratedHeader();

		for (var i = 0; i < 1000; i++)
		{
			using (writer.ClassScope(new TypeDeclarationOptions($"Class{i}", TypeDeclarationAccessibility.Public)))
			{
				writer.Line("// body");
			}
		}

		return writer.ToString();
	}
}
